CREATE TABLE IF NOT EXISTS runs (
    run_pk bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_namespace text NOT NULL,
    run_id text NOT NULL,
    source_path text NOT NULL,
    schema_version text NOT NULL CHECK (schema_version IN ('legacy', 'current')),
    summary_sha256 char(64) NOT NULL,
    trials_sha256 char(64) NOT NULL,
    cohort_sha256 char(64) NOT NULL,
    run_time_text text,
    git_head text,
    requested_split text,
    observed_splits text[] NOT NULL,
    n_items integer,
    llm_config text,
    judge_model text,
    judge_mode text,
    judge_prompt_version text,
    judge_prompt_hash text,
    answer_prompt_version text,
    answer_prompt_hash text,
    semantic_enabled boolean,
    dataset_name text,
    dataset_sha256 char(64),
    dataset_match_status text NOT NULL,
    config_json jsonb NOT NULL,
    corpus_source_json jsonb NOT NULL,
    summary_raw jsonb NOT NULL,
    imported_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT runs_source_run_unique UNIQUE (source_namespace, run_id),
    CONSTRAINT runs_source_path_unique UNIQUE (source_namespace, source_path)
);

CREATE TABLE IF NOT EXISTS run_compressor_metrics (
    run_pk bigint NOT NULL REFERENCES runs(run_pk) ON DELETE CASCADE,
    compressor text NOT NULL,
    compressor_config jsonb NOT NULL,
    n_trials integer NOT NULL CHECK (n_trials >= 0),
    input_reduction_pct double precision,
    net_input_reduction_pct double precision,
    context_reduction_pct double precision,
    legacy_net_reduction_pct double precision,
    semantic_sim double precision,
    entity_retention double precision,
    answer_accuracy double precision,
    answer_accuracy_retention_pct double precision,
    metric_coverage jsonb NOT NULL,
    raw_metrics jsonb NOT NULL,
    PRIMARY KEY (run_pk, compressor)
);

CREATE TABLE IF NOT EXISTS trials (
    trial_pk bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_pk bigint NOT NULL REFERENCES runs(run_pk) ON DELETE CASCADE,
    qid text NOT NULL,
    compressor text NOT NULL,
    repeat_index integer NOT NULL DEFAULT 0 CHECK (repeat_index >= 0),
    turn_index integer NOT NULL DEFAULT 0 CHECK (turn_index >= 0),
    conversation_id text,
    split text,
    qtype text,
    question text,
    reference_answer text,
    response text,
    input_tokens_raw integer,
    input_tokens integer,
    input_reduction_pct double precision,
    net_input_reduction_pct double precision,
    context_tokens_raw integer,
    context_tokens integer,
    context_reduction_pct double precision,
    legacy_net_reduction_pct double precision,
    semantic_sim double precision,
    entity_retention double precision,
    answer_accuracy double precision,
    satisfied_facts integer,
    total_facts integer,
    correct boolean,
    judge boolean,
    judge_prompt_version text,
    judge_prompt_hash text,
    judge_mode text,
    fact_results jsonb NOT NULL,
    compressor_info jsonb NOT NULL,
    record_sha256 char(64) NOT NULL,
    raw_record jsonb NOT NULL,
    CONSTRAINT trials_unique_item UNIQUE (run_pk, qid, compressor, repeat_index, turn_index),
    CONSTRAINT trials_run_compressor_fk FOREIGN KEY (run_pk, compressor)
        REFERENCES run_compressor_metrics(run_pk, compressor) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS trials_run_qid_idx ON trials (run_pk, qid);
CREATE INDEX IF NOT EXISTS runs_dataset_idx ON runs (dataset_name, dataset_sha256);
